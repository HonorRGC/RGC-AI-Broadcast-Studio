from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent
ENV_PATH = ROOT / ".env"

LAUNCHER_FIELDS = [
    ("USE_OPENAI", "true"),
    ("OPENAI_API_KEY", ""),
    ("OPENAI_MODEL", "gpt-5.5"),
    ("USE_ELEVENLABS", "true"),
    ("ELEVENLABS_API_KEY", ""),
    ("LEAD_VOICE_ID", ""),
    ("COLOR_VOICE_ID", ""),
    ("PIT_VOICE_ID", ""),
    ("OVERLAY_EVENT_TITLE", "RGC AI Broadcast"),
    ("OVERLAY_RACE_SPONSOR", ""),
    ("OVERLAY_SERIES_NAME", ""),
    ("USE_SPONSOR_READS", "true"),
    ("SPONSOR_READ_NAME", ""),
    ("SPONSOR_READ_CAUSE", ""),
    ("USE_LEAGUE_DRIVER_NOTES", "false"),
    ("LEAGUE_DRIVERS_CSV", "league/drivers.csv"),
    ("LEAGUE_STATS_CSV", "league/stats.csv"),
]


def load_env_file(path=ENV_PATH):
    values = {}
    path = Path(path)
    if not path.exists():
        return values

    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def save_env_file(values, path=ENV_PATH):
    lines = [
        "# Generated by RGC AI Broadcast Studio launcher.",
        "# You can still edit this file manually if needed.",
        "",
    ]
    for key, default in LAUNCHER_FIELDS:
        lines.append(f"{key}={values.get(key, default)}")
    lines.append("")
    Path(path).write_text("\n".join(lines), encoding="utf-8")


def launcher_defaults(existing=None):
    existing = existing or {}
    return {key: existing.get(key, default) for key, default in LAUNCHER_FIELDS}


def ensure_league_files(root=ROOT):
    root = Path(root)
    league_dir = root / "league"
    league_dir.mkdir(exist_ok=True)

    copied = []
    for name in ("drivers.csv", "stats.csv"):
        source = root / "league.example" / name
        target = league_dir / name
        if source.exists() and not target.exists():
            shutil.copyfile(source, target)
            copied.append(str(target))
    return copied


def broadcast_command():
    return [
        sys.executable,
        str(ROOT / "app.py"),
        "--overlay",
        "--camera-mode",
        "auto",
        "--incident-replay",
        "auto",
    ]


def launch_broadcast(helper_mode=False):
    env = os.environ.copy()
    if helper_mode:
        env["USE_OPENAI"] = "false"
        env["USE_ELEVENLABS"] = "false"
    subprocess.Popen(broadcast_command(), cwd=ROOT, env=env)


def run_gui():
    import tkinter as tk
    from tkinter import messagebox

    existing = launcher_defaults(load_env_file())
    root = tk.Tk()
    root.title("RGC AI Broadcast Studio")
    root.geometry("760x720")

    tk.Label(
        root,
        text="RGC AI Broadcast Studio",
        font=("Segoe UI", 18, "bold"),
    ).pack(pady=(14, 4))
    tk.Label(
        root,
        text="Configure your broadcast, league notes, stats, voices, and overlay.",
        font=("Segoe UI", 10),
    ).pack(pady=(0, 10))

    frame = tk.Frame(root)
    frame.pack(fill="both", expand=True, padx=18)

    entries = {}
    for row, (key, _default) in enumerate(LAUNCHER_FIELDS):
        tk.Label(frame, text=key, anchor="w", width=24).grid(
            row=row,
            column=0,
            sticky="w",
            pady=3,
        )
        entry = tk.Entry(frame, width=70)
        entry.insert(0, existing.get(key, ""))
        entry.grid(row=row, column=1, sticky="ew", pady=3)
        entries[key] = entry

    frame.columnconfigure(1, weight=1)

    status = tk.StringVar(value=f"Settings file: {ENV_PATH}")
    tk.Label(root, textvariable=status, anchor="w").pack(fill="x", padx=18, pady=(8, 0))

    def collect_values():
        return {key: entry.get().strip() for key, entry in entries.items()}

    def save_settings():
        save_env_file(collect_values())
        status.set(f"Saved settings to {ENV_PATH}")

    def create_league_files():
        copied = ensure_league_files()
        if copied:
            messagebox.showinfo("League files created", "\n".join(copied))
        else:
            messagebox.showinfo(
                "League files ready",
                "league/drivers.csv and league/stats.csv already exist.",
            )

    def start_full_ai():
        save_settings()
        launch_broadcast(helper_mode=False)
        status.set("Started full AI broadcast.")

    def start_helper():
        save_settings()
        launch_broadcast(helper_mode=True)
        status.set("Started broadcast helper mode. OpenAI and ElevenLabs are disabled.")

    buttons = tk.Frame(root)
    buttons.pack(fill="x", padx=18, pady=16)
    tk.Button(buttons, text="Save Settings", command=save_settings).pack(
        side="left",
        padx=4,
    )
    tk.Button(buttons, text="Create League Files", command=create_league_files).pack(
        side="left",
        padx=4,
    )
    tk.Button(buttons, text="Start Full AI Broadcast", command=start_full_ai).pack(
        side="left",
        padx=4,
    )
    tk.Button(buttons, text="Start Broadcast Helper", command=start_helper).pack(
        side="left",
        padx=4,
    )

    root.mainloop()


def main():
    run_gui()


if __name__ == "__main__":
    main()

